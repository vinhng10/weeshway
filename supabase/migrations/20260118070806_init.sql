CREATE OR REPLACE FUNCTION public.manage_project_lifecycle()
 RETURNS trigger
 LANGUAGE plpgsql
AS $function$BEGIN
    -- Canceled projects are immutable
    IF OLD.status = 'Cancel' THEN
        RAISE EXCEPTION 'A Canceled project cannot be modified.';
    END IF;

    -- Released projects can only change status to Cancel
    IF OLD.status = 'Release' THEN
        IF NEW.status = 'Draft' THEN
            RAISE EXCEPTION 'Cannot move a Released project back to Draft.';
        END IF;
        
        IF NEW::text IS DISTINCT FROM OLD::text AND NEW.status = OLD.status THEN
            RAISE EXCEPTION 'This project is Released. Only the Status can be changed to Cancel.';
        END IF;
    END IF;

    -- Validate required fields before releasing
    IF NEW.status = 'Release' AND OLD.status = 'Draft' THEN
        IF NEW.style IS NULL OR NEW.level IS NULL OR 
           NEW.price IS NULL OR NEW.spots IS NULL OR NEW.start_at IS NULL OR 
           NEW.end_at IS NULL OR NEW.location_id IS NULL THEN
            RAISE EXCEPTION 'Cannot release: Missing required project details.';
        END IF;
    END IF;

    RETURN NEW;
END;$function$
;

CREATE OR REPLACE VIEW "public"."recommendations"
  WITH (security_invoker = true)
  AS  SELECT ri.id,
    ri.created_at,
    ri.wish_id,
    ri.project_id,
    ri.score
   FROM (public.recommendation_items ri
     JOIN public.projects p ON ((ri.project_id = p.id)))
  WHERE ((ri.created_at >= (now() - '3 mons'::interval)) AND (p.status <> 'Cancel'::public.status) AND (p.start_at >= now()));


CREATE OR REPLACE VIEW "public"."stats"
  WITH (security_invoker = true)
  AS  SELECT p.user_id,
    sum(p.price) AS total_earnings,
    count(b.id) AS booking_count,
    p.currency,
    date_trunc('month'::text, now()) AS current_month
   FROM (public.bookings b
     JOIN public.projects p ON ((b.project_id = p.id)))
  WHERE ((b.status = 'Succeeded'::public.stripe_payment_status) AND (b.updated_at >= date_trunc('month'::text, now())))
  GROUP BY p.user_id, p.currency;


