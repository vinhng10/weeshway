CREATE OR REPLACE FUNCTION util.process_jobs(queue_name text, edge_function_name text, batch_size integer DEFAULT 10, max_requests integer DEFAULT 10, timeout_milliseconds integer DEFAULT ((60) * 1000))
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$declare
  job_batches jsonb[];
  batch jsonb;
begin
  with
    -- Use the dynamic _queue_name in the pgmq.read call
    numbered_jobs as (
      select
        message || jsonb_build_object('jobId', msg_id) as job_info,
        (row_number() over (order by 1) - 1) / batch_size as batch_num
      from pgmq.read(
        queue_name => queue_name,
        vt => timeout_milliseconds / 1000,
        qty => max_requests * batch_size
      )
    ),
    -- Group jobs into batches
    batched_jobs as (
      select
        jsonb_agg(job_info) as batch_array,
        batch_num
      from numbered_jobs
      group by batch_num
    )
  -- Aggregate all batches into array
  select array_agg(batch_array)
  from batched_jobs
  into job_batches;

  -- Exit if no jobs were found to process
  if job_batches is null then
    return;
  end if;

  -- Invoke the specified edge function for each batch
  foreach batch in array job_batches loop
    perform util.invoke_edge_function(
      name => edge_function_name,
      body => batch,
      timeout_milliseconds => timeout_milliseconds
    );
  end loop;
end;$function$
;

CREATE OR REPLACE FUNCTION util.project_url()
 RETURNS text
 LANGUAGE plpgsql
 SECURITY DEFINER
AS $function$
declare
  secret_value text;
begin
  -- Retrieve the project URL from Vault
  select decrypted_secret into secret_value from vault.decrypted_secrets where name = 'project_url';
  return secret_value;
end;
$function$
;

